for (const [command, expected, rule] of CASES) {
  test(`${expected.toUpperCase().padEnd(5)} ${command.replace(/\n/g, '\\n')}`, () => {
    const res = bash(command);
    assert.equal(res.decision, expected, `decision for: ${command}\n${res.summary}`);
    if (rule) assert.ok(res.findings.some((f) => f.rule === rule), `expected rule ${rule}, got: ${res.findings.map((f) => f.rule).join(', ')}`);
  });
}

test('every finding has a human-readable reason', () => {
  for (const [command] of CASES) {
    for (const f of bash(command).findings) {
      assert.ok(typeof f.reason === 'string' && f.reason.length > 10, `${command} → ${JSON.stringify(f)}`);
    }
  }
});
